constexpr int hex_char_to_int(char c) {
    return (c >= '0' && c <= '9') ? (c - '0') :
           (c >= 'a' && c <= 'f') ? (c - 'a' + 10) :
           (c >= 'A' && c <= 'F') ? (c - 'A' + 10) : -1;
}

constexpr unsigned int parse_hex_word(const char* s, int offset) {
    unsigned int val = 0;
    for (int i = 0; i < 8; i++) {
        val = (val << 4) | hex_char_to_int(s[offset + i]);
    }
    return val;
}

